"""Export the flow contract for the frontend (specs/contracts.md C1).

    uv run python scripts/export_schema.py

Writes:
  contracts/flow.schema.json        JSON Schema of the Flow document
  contracts/node-types.json         palette catalogue (same as GET /api/node-types)
  contracts/examples/invalid_*.json one invalid flow per rule, with the expected message
  web/src/types/flow.ts             TypeScript types (needs Node; skipped if npx is missing)
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.flow.cases import INVALID_CASES, build_case  # noqa: E402
from app.flow.schema import Flow, node_type_schemas  # noqa: E402
from app.flow.validate import validate_flow  # noqa: E402


def write_json(path: Path, data: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


def main() -> int:
    contracts = ROOT / "contracts"
    schema = Flow.model_json_schema()
    schema["title"] = "Flow"
    write_json(contracts / "flow.schema.json", schema)
    write_json(contracts / "node-types.json", node_type_schemas())

    for name in sorted(INVALID_CASES):
        flow, expected, for_publish = build_case(name)
        write_json(contracts / "examples" / f"invalid_{name}.json", {
            "_expected_message": expected,
            "_for_publish": for_publish,
            "_issues": validate_flow(flow, for_publish=for_publish),
            "flow": flow,
        })

    ts_out = ROOT / "web" / "src" / "types" / "flow.ts"
    npx = shutil.which("npx")
    if npx is None:
        print("npx not found: skipped web/src/types/flow.ts")
        return 0
    ts_out.parent.mkdir(parents=True, exist_ok=True)
    banner = "/* Generated by scripts/export_schema.py from app/flow/schema.py. Do not edit by hand. */"
    result = subprocess.run(
        [npx, "--yes", "json-schema-to-typescript@15", "--input", str(contracts / "flow.schema.json"),
         "--output", str(ts_out), "--bannerComment", banner, "--unreachableDefinitions", "--maxItems=-1"],
        capture_output=True, text=True,
    )
    if result.returncode != 0:
        print(result.stderr or result.stdout)
        return result.returncode
    print(f"wrote {ts_out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
